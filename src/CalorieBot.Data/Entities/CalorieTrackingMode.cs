namespace CalorieBot.Data.Entities;

/// <summary>
/// Что именно контролирует пользователь. Значения задаю явно, потому что они уезжают в базу как int
/// и менять их порядок после первого релиза уже нельзя.
/// </summary>
public enum CalorieTrackingMode
{
    /// <summary>Следит только за калориями — БЖУ показываются справочно, без собственных лимитов.</summary>
    Calories = 0,

    /// <summary>Следит за БЖУ — лимиты по белкам/жирам/углеводам задаются напрямую, калории считаются из них.</summary>
    Macros = 1
}
